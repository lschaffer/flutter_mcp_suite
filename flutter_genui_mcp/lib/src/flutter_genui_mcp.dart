                final groups = _getToolsetGroups();
                final content = ListView(
                  shrinkWrap: true,
                  children: [
                    ...groups.map((group) {
                      final isEnabled = _isToolsetEnabled(group);
                      return CheckboxListTile(
                        title: Text(
                          group.name,
                          style: const TextStyle(
                            fontWeight: FontWeight.bold,
                            fontSize: 14,
                          ),
                        ),
                        subtitle: Text(
                          group.description,
