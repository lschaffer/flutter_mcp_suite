  Widget _buildGenuiConversationView(ThemeData theme) {
    if (_genuiController == null) {
      return const Center(child: CircularProgressIndicator());
    }

    final isGenerating = _genuiController!.isGenerating;
    return Column(
      children: [
        Expanded(
          child: AnimatedBuilder(
            animation: _genuiController!,
            builder: (context, _) {
              final entries = _genuiController!.entries;
              if (entries.isEmpty) {
                return _buildWelcomeWidget(theme);
              }
              return ListView(
                controller: _scrollCtrl,
                padding: const EdgeInsets.only(bottom: 24),
                children: [
                  for (final entry in entries)
                    _buildGenuiEntry(context, entry, theme),
                ],
              );
            },
          ),
        ),
        if (isGenerating)
          Padding(
            padding: const EdgeInsets.symmetric(
              vertical: 8.0,
              horizontal: 16.0,
            ),
            child: Row(
              children: [
                const SizedBox(
                  width: 14,
                  height: 14,
                  child: CircularProgressIndicator(strokeWidth: 2),
                ),
                const SizedBox(width: 8),
                Expanded(
                  child: Text(
                    'GenUI Agent is generating interactive widgets and tool calls...',
                    style: theme.textTheme.bodySmall?.copyWith(
                      color: Colors.grey,
                    ),
                    overflow: TextOverflow.ellipsis,
                    maxLines: 1,
                  ),
                ),
              ],
            ),
          ),
        _buildInputBar(theme),
      ],
    );
  }

  Widget _buildGenuiEntry(
    BuildContext context,
    GenuiChatEntry entry,
    ThemeData theme,
  ) {
    final isDark = theme.brightness == Brightness.dark;

    switch (entry.kind) {
      case GenuiChatEntryKind.user:
        return Padding(
          padding: const EdgeInsets.symmetric(vertical: 6, horizontal: 16),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.end,
            mainAxisSize: MainAxisSize.min,
            children: [
              if (entry.attachments != null && entry.attachments!.isNotEmpty)
                Padding(
                  padding: const EdgeInsets.only(bottom: 4),
                  child: Wrap(
                    spacing: 6,
                    runSpacing: 4,
                    alignment: WrapAlignment.end,
                    children: [
                      for (final att in entry.attachments!)
                        Chip(
                          avatar: Icon(
                            att.mimeType.startsWith('image/')
                                ? Icons.image_outlined
                                : Icons.description_outlined,
                            size: 14,
                          ),
                          label: Text(
                            att.name,
                            style: const TextStyle(fontSize: 11),
                          ),
                          visualDensity: VisualDensity.compact,
                          padding: EdgeInsets.zero,
                        ),
                    ],
                  ),
                ),
              Row(
                mainAxisAlignment: MainAxisAlignment.end,
                crossAxisAlignment: CrossAxisAlignment.end,
                children: [
                  IconButton(
                    icon: Icon(
                      Icons.content_copy_outlined,
                      size: 14,
                      color: theme.colorScheme.onSurfaceVariant.withValues(
                        alpha: 0.6,
                      ),
                    ),
                    tooltip: 'Copy prompt',
                    visualDensity: VisualDensity.compact,
                    padding: const EdgeInsets.all(4),
                    constraints: const BoxConstraints(),
                    onPressed: () {
                      Clipboard.setData(ClipboardData(text: entry.text));
                      ScaffoldMessenger.of(context).showSnackBar(
                        const SnackBar(
                          content: Text('Prompt copied to clipboard'),
                          duration: Duration(seconds: 1),
                        ),
                      );
                    },
                  ),
                  const SizedBox(width: 4),
                  Flexible(
                    child: Container(
                      padding: const EdgeInsets.all(12),
                      decoration: BoxDecoration(
                        color: theme.colorScheme.primary.withValues(
                          alpha: 0.12,
                        ),
                        borderRadius: BorderRadius.circular(16),
                      ),
                      child: Text(entry.text),
                    ),
                  ),
                ],
              ),
            ],
          ),
        );
      case GenuiChatEntryKind.assistant:
        if (entry.text.trim().isEmpty) return const SizedBox.shrink();
        return Padding(
          padding: const EdgeInsets.symmetric(vertical: 6, horizontal: 16),
          child: Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              CircleAvatar(
                radius: 14,
                backgroundColor: isDark
                    ? Colors.white.withValues(alpha: 0.1)
                    : theme.colorScheme.primaryContainer,
                child: Icon(
                  Icons.auto_awesome_rounded,
                  size: 16,
                  color: isDark
                      ? Colors.white
                      : theme.colorScheme.onPrimaryContainer,
                ),
              ),
              const SizedBox(width: 8),
              Flexible(
                child: Container(
                  padding: const EdgeInsets.all(12),
                  decoration: BoxDecoration(
                    color: isDark
                        ? Colors.white.withValues(alpha: 0.05)
                        : Colors.black.withValues(alpha: 0.04),
                    borderRadius: BorderRadius.circular(16),
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      MarkdownBody(
                        data: entry.text,
                        styleSheet: markdownStyleSheetFromMaterialUiTheme(
                          theme,
                        ),
                        syntaxHighlighter: McpMarkdownSyntaxHighlighter(
                          isDark: isDark,
                        ),
                      ),
                      const SizedBox(height: 6),
                      Align(
                        alignment: Alignment.bottomRight,
                        child: InkWell(
                          onTap: () {
                            Clipboard.setData(ClipboardData(text: entry.text));
                            ScaffoldMessenger.of(context).showSnackBar(
                              const SnackBar(
                                content: Text('Response copied to clipboard'),
                                duration: Duration(seconds: 1),
                              ),
                            );
                          },
                          borderRadius: BorderRadius.circular(4),
                          child: Padding(
                            padding: const EdgeInsets.all(4.0),
                            child: Row(
                              mainAxisSize: MainAxisSize.min,
                              children: [
                                Icon(
                                  Icons.content_copy_outlined,
                                  size: 13,
                                  color: theme.colorScheme.onSurfaceVariant
                                      .withValues(alpha: 0.6),
                                ),
                                const SizedBox(width: 4),
                                Text(
                                  'Copy',
                                  style: TextStyle(
                                    fontSize: 10,
                                    color: theme.colorScheme.onSurfaceVariant
                                        .withValues(alpha: 0.6),
                                  ),
                                ),
                              ],
                            ),
                          ),
                        ),
                      ),
                    ],
                  ),
                ),
              ),
            ],
          ),
        );
      case GenuiChatEntryKind.surface:
        if (entry.surfaceId != null) {
          return Card(
            margin: const EdgeInsets.symmetric(vertical: 8, horizontal: 16),
            elevation: 2,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(12),
            ),
            child: Padding(
              padding: const EdgeInsets.all(12),
              child: Surface(
                surfaceContext: _genuiController!.contextFor(entry.surfaceId!),
              ),
            ),
          );
        }
        return const SizedBox.shrink();
      case GenuiChatEntryKind.error:
        return Container(
          margin: const EdgeInsets.symmetric(vertical: 4, horizontal: 16),
          padding: const EdgeInsets.all(10),
          decoration: BoxDecoration(
            color: theme.colorScheme.errorContainer,
            borderRadius: BorderRadius.circular(8),
          ),
          child: Text(
            entry.text,
            style: TextStyle(
              color: theme.colorScheme.onErrorContainer,
              fontFamily: 'monospace',
              fontSize: 12,
            ),
          ),
        );
    }
  }

