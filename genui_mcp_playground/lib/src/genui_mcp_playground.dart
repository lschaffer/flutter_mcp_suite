    return Center(
      child: SingleChildScrollView(
        child: Padding(
          padding: const EdgeInsets.all(32.0),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Icon(
                Icons.auto_awesome_rounded,
                size: 72,
                color: theme.colorScheme.primary.withValues(alpha: 0.5),
              ),
              const SizedBox(height: 16),
              Text(
                'GenUI Playground Ready',
                style: theme.textTheme.titleLarge?.copyWith(
                  fontWeight: FontWeight.bold,
                ),
              ),
              const SizedBox(height: 8),
              Text(
                'Interactive GenUI widgets will be dynamically rendered directly from agent responses and MCP tool calls.',
                textAlign: TextAlign.center,
                style: theme.textTheme.bodyMedium?.copyWith(color: Colors.grey),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildAttachmentPreviews() {
    if (_attachments.isEmpty) return const SizedBox.shrink();
    return Container(
      height: 50,
      padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
      child: ListView.builder(
        scrollDirection: Axis.horizontal,
        itemCount: _attachments.length,
        itemBuilder: (ctx, idx) {
          final att = _attachments[idx];
          return Container(
            margin: const EdgeInsets.only(right: 8),
            child: InputChip(
              label: Text(att.name, style: const TextStyle(fontSize: 11)),
              onDeleted: () {
                setState(() {
                  _attachments.removeAt(idx);
                });
              },
            ),
          );
        },
      ),
    );
  }

  Widget _buildInputBar(ThemeData theme) {
    final isGen = _genuiController?.isGenerating ?? false;
    final showButton =
        _inputCtrl.text.isNotEmpty || _attachments.isNotEmpty || !isGen;

    return Container(
      decoration: BoxDecoration(
        color: theme.colorScheme.surface,
        border: Border(top: BorderSide(color: theme.dividerColor)),
      ),
      child: SafeArea(
        top: false,
        child: Padding(
          padding: const EdgeInsets.all(8.0),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              ActiveSkillBanner(
                controller: _controller,
                padding: const EdgeInsets.only(bottom: 6.0),
              ),
              _buildAttachmentPreviews(),
              SubPromptListEditor(
                controller: _inputCtrl,
                chatMode: _chatMode,
                availableToolGroups: _getToolsetGroups()
                    .where((g) => _isToolsetEnabled(g))
                    .map(
                      (g) => ToolGroup(
                        name: g.name,
                        toolNames: g.tools.map((t) => t.name).toList(),
                      ),
                    )
                    .toList(),
                minLines: 1,
                maxLines: 6,
                hintText: isGen
                    ? 'GenUI Agent is working...'
                    : 'Ask the GenUI agent to render UI or run tools...',
              ),
              const SizedBox(height: 8),
              Row(
                children: [
                  IconButton(
                    icon: const Icon(Icons.attach_file_outlined),
                    tooltip: 'Attach Files / Images',
                    onPressed: isGen ? null : _pickAttachments,
                  ),
                  const Spacer(),
                  if (isGen)
                    const Padding(
                      padding: EdgeInsets.symmetric(horizontal: 12.0),
                      child: SizedBox(
                        width: 20,
                        height: 20,
                        child: CircularProgressIndicator(strokeWidth: 2.5),
                      ),
                    )
                  else
                    IconButton(
                      icon: Icon(
                        Icons.send_rounded,
                        color: showButton &&
                                _controller.activeLlmConfig.isConfigured
                            ? theme.colorScheme.primary
                            : Colors.grey,
                      ),
                      onPressed: showButton &&
                              _controller.activeLlmConfig.isConfigured
                          ? _handleSend
                          : null,
                    ),
                ],
              ),
            ],
          ),
        ),
      ),
    );
  }
