  }

  void _scrollToBottom() {
    if (_scrollCtrl.hasClients) {
      _scrollCtrl.animateTo(
        _scrollCtrl.position.maxScrollExtent,
        duration: const Duration(milliseconds: 250),
        curve: Curves.easeOut,
      );
    }
  }

  LlmConfig _getActiveLlmConfig() {
    if (_useCustomLlm) {
      return LlmConfig(
        provider: _customProvider,
        model: _customModelCtrl.text.trim(),
        apiKey: _customApiKeyCtrl.text.trim(),
        baseUrl: _customBaseUrlCtrl.text.trim(),
        temperature: double.tryParse(_customTempCtrl.text.trim()) ?? 0.2,
        maxTokens: int.tryParse(_customMaxTokensCtrl.text.trim()) ?? 0,
        maxToolOutputSize:
            int.tryParse(_customMaxToolOutputSizeCtrl.text.trim()) ?? 2560000,
        tokenWarningThreshold:
            int.tryParse(_customTokenWarningThresholdCtrl.text.trim()) ??
            1500000,
        topK: int.tryParse(_customTopKCtrl.text.trim()),
        topP: double.tryParse(_customTopPCtrl.text.trim()),
        repeatPenalty: double.tryParse(_customRepeatPenaltyCtrl.text.trim()),
        seed: int.tryParse(_customSeedCtrl.text.trim()),
        thinking: _customThinking,
        isSlm: _customIsSlm,
        isMultiModal: _customIsMultiModal,
        useNativeToolCall: _customUseNativeTool,
        useStreaming: _customUseStreaming,
      );
    }
    return _controller.llmConfig;
  }

  void _syncCustomLlmInputs(LlmConfig config) {
    _customProvider = config.provider;
    _customModelCtrl.text = config.model;
    _customApiKeyCtrl.text = config.apiKey;
    _customBaseUrlCtrl.text = config.baseUrl;
    _customTempCtrl.text = config.temperature.toString();
    _customMaxTokensCtrl.text = config.maxTokens.toString();
    _customMaxToolOutputSizeCtrl.text = config.maxToolOutputSize.toString();
    _customTokenWarningThresholdCtrl.text =
        config.tokenWarningThreshold.toString();
    _customTopKCtrl.text = config.topK?.toString() ?? '';
    _customTopPCtrl.text = config.topP?.toString() ?? '';
    _customRepeatPenaltyCtrl.text = config.repeatPenalty?.toString() ?? '';
    _customSeedCtrl.text = config.seed?.toString() ?? '';
    _customThinking = config.thinking;
    _customIsSlm = config.isSlm;
    _customIsMultiModal = config.isMultiModal;
    _customUseNativeTool = config.useNativeToolCall;
    _customUseStreaming = config.useStreaming;
  }

  List<_ToolsetGroup> _getToolsetGroups() {
    final groups = <_ToolsetGroup>[];

    final weatherTools = _controller.localTools
        .where(
          (t) =>
              t.name == 'get_weather_forecast' ||
              t.name == 'get_current_weather' ||
              t.name == 'get_hourly_forecast' ||
              t.name == 'get_daily_forecast' ||
              t.name == 'geocode_weather_city',
        )
        .map((t) => t.toMCPTool())
        .toList();
    if (weatherTools.isNotEmpty) {
      groups.add(
        _ToolsetGroup(
          name: 'Weather API',
          description:
              'Current, hourly, and daily forecasts, plus city geocoding via Open-Meteo.',
          tools: weatherTools,
        ),
      );
    }

    final interactiveChartTools = _controller.localTools
        .where((t) => t.name == 'create_chart_png')
        .map((t) => t.toMCPTool())
        .toList();
    if (interactiveChartTools.isNotEmpty) {
      groups.add(
        _ToolsetGroup(
          name: 'Chart generator (Interactive)',
          description:
              'Generate interactive JSON charts rendered via fl_chart.',
          tools: interactiveChartTools,
        ),
      );
    }

    final imageChartTools = _controller.localTools
        .where((t) => t.name == 'chart2png')
        .map((t) => t.toMCPTool())
        .toList();
    if (imageChartTools.isNotEmpty) {
      groups.add(
        _ToolsetGroup(
          name: 'Chart generator (PNG Image)',
          description: 'Generate flat PNG image charts from canvas rendering.',
          tools: imageChartTools,
        ),
      );
    }

    final sshTools = _controller.localTools
        .where(
          (t) =>
              t.name.startsWith('ssh_') ||
              t.name.startsWith('sftp_') ||
              t.name == 'ssh_execute_command',
        )
        .map((t) => t.toMCPTool())
        .toList();
    if (sshTools.isNotEmpty) {
      groups.add(
        _ToolsetGroup(
          name: 'SSH/SFTP',
          description:
              'Execute remote commands, list directories, read, and transfer files via SSH/SFTP.',
          tools: sshTools,
        ),
      );
    }

    final otherTools = _controller.localTools
        .where(
          (t) =>
              t.name != 'get_weather_forecast' &&
              t.name != 'get_current_weather' &&
              t.name != 'get_hourly_forecast' &&
              t.name != 'get_daily_forecast' &&
              t.name != 'geocode_weather_city' &&
              t.name != 'create_chart_png' &&
              t.name != 'chart2png' &&
              !t.name.startsWith('ssh_') &&
              !t.name.startsWith('sftp_'),
        )
        .map((t) => t.toMCPTool())
        .toList();
    if (otherTools.isNotEmpty) {
      groups.add(
        _ToolsetGroup(
          name: 'Custom Local Tools',
          description:
              'Dart-native tools registered specifically in this playground instance.',
          tools: otherTools,
        ),
      );
    }

    for (final client in _controller.mcpClients) {
      final isExt = client.url.startsWith('http');
      groups.add(
        _ToolsetGroup(
          name: client.label,
          description: client.url,
          tools: client.availableTools,
          isExternal: isExt,
          isInstalled: !isExt,
        ),
      );
    }

    return groups;
  }

  bool _isToolsetEnabled(_ToolsetGroup group) {
    if (group.tools.isEmpty) return false;
    final enabled = _controller.enabledToolNames;
    return group.tools.every((t) => enabled.contains(t.name));
  }

  void _toggleToolsetGroup(_ToolsetGroup group, bool enable) {
    final updated = Set<String>.from(_controller.enabledToolNames);
    for (final t in group.tools) {
      if (enable) {
        updated.add(t.name);
      } else {
        updated.remove(t.name);
      }
    }
    _controller.updateEnabledTools(updated);
  }

  Future<void> _startPlayground() async {
    final activeLlm = _getActiveLlmConfig();
    if (!activeLlm.isConfigured && !widget.disableConfigDialog) {
      _showSettingsDialog();
      return;
    }

    setState(() {
      _playgroundStarted = true;
      _controller.systemPrompt = _systemPromptCtrl.text.trim();

      _genuiController?.dispose();
      _genuiController = McpGenuiChatController(
        llmConfig: activeLlm,
        tools: _controller.localTools,
        systemPrompt: _systemPromptCtrl.text.isNotEmpty
            ? _systemPromptCtrl.text
            : null,
        catalog: widget.genuiCatalog,
        catalogJson: widget.genuiCatalogJson,
        catalogItems: widget.genuiCatalogItems,
        clientFunctions: widget.clientFunctions,
        playgroundController: _controller,
      );
      _genuiController!.addListener(_onStateChange);
    });

    if (_initialPromptCtrl.text.isNotEmpty) {
      final prompt = _initialPromptCtrl.text;
      _inputCtrl.text = prompt;
      _handleSend();
    }
  }

  void _resetPlayground() {
    _genuiController?.dispose();
    _genuiController = null;
    setState(() {
      _playgroundStarted = false;
      _controller.clearChat();
      _attachments.clear();
    });
  }

  Future<void> _handleSend() async {
    final text = _inputCtrl.text.trim();
    if (text.isEmpty && _attachments.isEmpty) return;

    if (_genuiController == null) {
      _startPlayground();
      return;
    }

    if (_genuiController!.isGenerating) return;

    final atts = List<MessageAttachment>.from(_attachments);
    _inputCtrl.clear();
    _attachments.clear();

    _genuiController!.sendMessage(text, attachments: atts);
  }

  Future<void> _pickAttachments() async {
    try {
      final files = await FilePicker.pickFiles();

      if (files.isNotEmpty) {
        for (final file in files) {
          final bytes = await file.readAsBytes();
          final name = file.name;
          final mime = _mimeFromExtension(name);
          final size = bytes.length;
          _attachments.add(
            MessageAttachment(
              id: const Uuid().v4(),
              name: name,
              path: file.path ?? '',
              bytes: bytes,
              mimeType: mime,
              size: size,
            ),
          );
        }
        setState(() {});
      }
    } catch (e) {
      debugPrint('Error picking files: $e');
    }
  }

